// Functions
function greet(name) {  
    return "Hello, " + name + "!";
}

function add(a, b) {
    return a + b;
}

// Calling the functions
let greeting = greet("Alice");
let sum = add(5, 10);

// Output the results
console.log(greeting); // Output: Hello, Alice!
console.log("Sum:", sum); // Output: Sum: 15
