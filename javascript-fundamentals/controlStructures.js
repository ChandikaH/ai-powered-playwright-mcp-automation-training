// If-Else
let age = 30;
if (age < 18) {
    console.log("You are a minor.");
} else {
    console.log("You are an adult.");
}

// For Loop
for (let i = 0; i < 5; i++) {
    console.log("Iteration:", i);
}

// While Loop
let count = 0;
while (count < 5) {
    console.log("Count:", count);
    count++;
}

// Switch Statement
let day = "Monday";
switch (day) {
    case "Monday":
        console.log("Start of the week.");
        break;
    case "Friday":
        console.log("End of the week.");
        break;
    default:
        console.log("Midweek day.");
}